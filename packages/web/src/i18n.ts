export const DICTIONARY: Record<Lang, Record<Key, string>> = { en, de };

let current: Lang = 'en';

export function getLang(): Lang {
  return current;
}

export function setLang(lang: Lang): void {
  current = lang;
}

export function isLang(v: unknown): v is Lang {
  return v === 'en' || v === 'de';
}

/** Looks a string up in the current language and fills `{name}` placeholders. A numeric `n` is formatted for the language. */
export function t(key: Key, params: Record<string, string | number> = {}): string {
  const dict = DICTIONARY[current];
  const oneKey = `${key}.one` as Key;
  const template = params['n'] === 1 && oneKey in dict ? dict[oneKey] : dict[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) => {
    const v = params[name];
    // The count `n` is formatted for the language; it selects the singular form above from its numeric value.
    if (typeof v === 'number' && name === 'n') return formatNumber(v);
    return String(v ?? `{${name}}`);
  });
}

/** The text of the core in the current language (generator names, option labels). */
export function local(text: LocalText): string {
  return text[current];
}

/** Number formatting for display only (the exported bytes never contain it). */
export function formatNumber(n: number, fractionDigits = 0): string {
  return new Intl.NumberFormat(current === 'de' ? 'de-DE' : 'en-US', { minimumFractionDigits: fractionDigits, maximumFractionDigits: fractionDigits }).format(n);
}
