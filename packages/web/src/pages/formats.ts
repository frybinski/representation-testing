import { createDefaultRegistry, extensionOf, parseModel, type Formalism, type GeneratorDefinition, type OptionSpec } from '@repr-werkbank/core';
import { el } from '../dom.ts';
import { local, t } from '../i18n.ts';
import { parseSvg } from '../views/diagram-view.ts';
import { BPMN_EXAMPLE, PNML_EXAMPLE } from './formats-example.ts';
import { pageFrame, section } from './page.ts';

/**
 * Reference material per generator id: the documents of the repository that define the format (grammar, schema, rules). The page lists
 * every generator of the registry; one without an entry here still appears with its description, options and a generated example, so a
 * new generator needs no change in this file to show up (§7).
 */
const REFERENCE: Record<string, { file: string; kind: 'rules' | 'schema' }[]> = {
  json: [
    { file: 'json-representation.md', kind: 'rules' },
    { file: 'json-representation.schema.json', kind: 'schema' },
  ],
  mermaid: [{ file: 'mermaid-representation.md', kind: 'rules' }],
  compact: [{ file: 'compact-notation.md', kind: 'rules' }],
  verbalization: [{ file: 'verbalization.md', kind: 'rules' }],
  diagram: [{ file: 'diagram.md', kind: 'rules' }],
  'structure-report': [{ file: 'structure-report.md', kind: 'rules' }],
  'structure-report-json': [{ file: 'structure-report.schema.json', kind: 'schema' }],
};
const BUNDLE_REFERENCE = [
  { file: 'bundle.md', kind: 'rules' as const },
  { file: 'bundle.schema.json', kind: 'schema' as const },
];

// Only the documents named above are bundled (a glob over docs/ would pull in every note of the repository).
const docs = import.meta.glob(
  [
    '../../../../docs/json-representation.md',
    '../../../../docs/json-representation.schema.json',
    '../../../../docs/mermaid-representation.md',
    '../../../../docs/compact-notation.md',
    '../../../../docs/verbalization.md',
    '../../../../docs/diagram.md',
    '../../../../docs/structure-report.md',
    '../../../../docs/structure-report.schema.json',
    '../../../../docs/bundle.md',
    '../../../../docs/bundle.schema.json',
  ],
  { query: '?raw', import: 'default', eager: false },
) as Record<string, () => Promise<string>>;

const FORMALISM_NAME: Record<Formalism, string> = { bpmn: 'BPMN 2.0 XML', pnml: 'PNML' };

/** The reference document `file` of docs/, or null when this build does not have it. */
export async function loadDoc(file: string): Promise<string | null> {
  const load = docs[`../../../../docs/${file}`];
  return load ? load() : null;
}

function reference(files: readonly { file: string; kind: 'rules' | 'schema' }[]): HTMLElement[] {
  return files.map(({ file, kind }) => {
    const pre = el('pre', { class: 'report reference', tabindex: '0' });
    const details = el('details', { class: 'reference-box' }, el('summary', {}, t(kind === 'schema' ? 'formats.schema' : 'formats.rules'), ` (${file})`), pre);
    // The document is read when the box is opened; nothing is fetched (the build contains it).
    details.addEventListener('toggle', () => {
      if (!details.open || pre.textContent !== '') return;
      pre.textContent = t('formats.loading');
      void loadDoc(file).then((text) => (pre.textContent = text ?? t('formats.missing')));
    });
    return details;
  });
}

function optionLine(spec: OptionSpec): HTMLElement {
  return el('li', {}, el('strong', {}, local(spec.label)), ` (${spec.key}, ${t('formats.default')}: ${String(spec.default)}): ${local(spec.description)}`);
}

/** The example of a generator: generated by the core from the built-in model of the first formalism it supports. */
function example(def: GeneratorDefinition, registry: ReturnType<typeof createDefaultRegistry>): HTMLElement {
  const formalism: Formalism = def.formalisms.includes('bpmn') ? 'bpmn' : 'pnml';
  const box = el('div', { class: 'format-example' }, el('h3', { class: 'composer-subtitle' }, t('formats.example', { formalism: FORMALISM_NAME[formalism] })));
  try {
    const model = parseModel(formalism === 'bpmn' ? BPMN_EXAMPLE : PNML_EXAMPLE);
    const out = registry.run(def.id, model);
    if (out.kind === 'image') {
      const svg = parseSvg(out.svg);
      if (svg) {
        svg.setAttribute('role', 'img');
        svg.setAttribute('aria-label', t('formats.diagramAlt'));
                svg.removeAttribute('width');
        svg.removeAttribute('height');
        box.append(el('div', { class: 'diagram-example' }, svg));
      }
    } else {
      box.append(el('pre', { class: 'report example', tabindex: '0' }, out.text));
    }
  } catch (e) {
    box.append(el('p', { class: 'muted' }, e instanceof Error ? e.message : String(e)));
  }
  return box;
}

/** Formats (FA-81): per representation a short description, the grammar or schema, and an example. Built from the registry. */
export function renderFormats(): HTMLElement {
  const registry = createDefaultRegistry();
  const sections = registry.list().map((def) =>
    el(
      'section',
      { class: 'page-section format', id: `format-${def.id}` },
      el('h2', { class: 'page-heading' }, local(def.name)),
      el('p', {}, local(def.description)),
      el(
        'p',
        { class: 'muted' },
        t('formats.meta', {
          formalisms: def.formalisms.map((f) => FORMALISM_NAME[f]).join(', '),
          extensions: [...new Set(def.formalisms.map((f) => `.${extensionOf(def, f)}`))].join(', '),
          kind: def.role === 'addition' ? t('formats.addition') : t(def.kind === 'image' ? 'formats.image' : 'formats.text'),
        }),
      ),
      ...(def.options.length > 0 ? [el('p', { class: 'strong' }, t('formats.options')), el('ul', { class: 'option-list' }, ...def.options.map(optionLine))] : []),
      example(def, registry),
      ...reference(REFERENCE[def.id] ?? []),
    ),
  );
  const sources = section(
    t('formats.sourcesTitle'),
    t('formats.sources'),
    el('details', { class: 'reference-box' }, el('summary', {}, 'BPMN'), el('pre', { class: 'report reference', tabindex: '0' }, BPMN_EXAMPLE)),
    el('details', { class: 'reference-box' }, el('summary', {}, 'PNML'), el('pre', { class: 'report reference', tabindex: '0' }, PNML_EXAMPLE)),
  );
  const bundle = el('section', { class: 'page-section format', id: 'format-bundle' }, el('h2', { class: 'page-heading' }, t('formats.bundleTitle')), el('p', {}, t('formats.bundle')), ...reference(BUNDLE_REFERENCE));
  return pageFrame(t('formats.title'), el('p', {}, t('formats.intro')), sources, ...sections, bundle);
}
