// @vitest-environment jsdom
import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';
import { createDefaultRegistry, VERSION } from '@repr-werkbank/core';
import { setLang } from '../src/i18n.ts';
import { LINKS } from '../src/links.ts';
import { citationText, renderAbout } from '../src/pages/about.ts';
import { loadDoc, renderFormats } from '../src/pages/formats.ts';
import { renderLegal } from '../src/pages/legal.ts';
import { hrefOf, parseRoute } from '../src/router.ts';
import { describeExample, listExamples } from '../src/examples.ts';
import { EXAMPLE_DESCRIPTIONS_DE } from '../src/examples-de.ts';

const root = join(import.meta.dirname, '../../..');

afterEach(() => setLang('en'));

describe('hash routing', () => {
  it('maps the hashes to routes and everything else to the workspace', () => {
    expect(parseRoute('')).toBe('workspace');
    expect(parseRoute('#/')).toBe('workspace');
    expect(parseRoute('#/about')).toBe('about');
    expect(parseRoute('#/formats/')).toBe('formats');
    expect(parseRoute('#/legal')).toBe('legal');
    expect(parseRoute('#/nope')).toBe('workspace');
    for (const r of ['workspace', 'about', 'formats', 'legal'] as const) expect(parseRoute(hrefOf(r))).toBe(r);
  });
});

describe('About (FA-80, FA-82)', () => {
  const text = (): string => renderAbout().textContent ?? '';

  it('carries the DOI link, the repository, the author, the version and the note on the verbalization, in both languages', () => {
    for (const lang of ['en', 'de'] as const) {
      setLang(lang);
      const page = renderAbout();
      const hrefs = [...page.querySelectorAll('a')].map((a) => a.getAttribute('href'));
      expect(hrefs).toContain(LINKS.doi);
      expect(hrefs).toContain(LINKS.repository);
      expect(hrefs).toContain('#/legal');
      expect(hrefs).toContain('./THIRD_PARTY_LICENSES.txt');
      expect(page.textContent).toContain('Copy That?');
      expect(page.textContent).toContain('ER 2026 Workshops');
      expect(page.textContent).toContain('Fabian Rybinski');
      expect(page.textContent).toContain(VERSION);
      expect(page.textContent).toContain('o200k_base');
    }
    expect(LINKS.doi).toBe('https://doi.org/10.1007/978-3-032-40377-3_3');
    expect(LINKS.repository).toBe('https://github.com/frybinski/representation-testing');
  });

  it('says what is rule-based and what was written by hand, and states privacy', () => {
    setLang('en');
    expect(text()).toMatch(/written by hand/);
    expect(text()).toMatch(/generated by rules/);
    expect(text()).toMatch(/not uploaded/);
    setLang('de');
    expect(text()).toMatch(/von Hand erstellt/);
    expect(text()).toMatch(/nicht hochgeladen/);
  });

  it('has the citation hint with name, version, year, author, and the same data as CITATION.cff', () => {
    expect(citationText()).toContain(`version ${VERSION}`);
    const cff = readFileSync(join(root, 'CITATION.cff'), 'utf8');
    expect(cff).toContain(`version: ${VERSION}`);
    expect(cff).toContain(`repository-code: "${LINKS.repository}"`);
    expect(cff).toContain('family-names: Rybinski');
    expect(cff).toContain('Karlsruhe Institute of Technology');
  });

  it('makes external links open in a new tab without giving the new page access to this one', () => {
    for (const a of renderAbout().querySelectorAll<HTMLAnchorElement>('a[href^="https://"]')) {
      expect(a.target).toBe('_blank');
      expect(a.rel).toContain('noopener');
    }
  });
});

describe('Legal (E-6)', () => {
  it('is marked as a placeholder', () => {
    expect(renderLegal().textContent).toMatch(/Placeholder\. Content follows/);
    setLang('de');
    expect(renderLegal().textContent).toMatch(/Platzhalter\. Inhalt folgt/);
  });
});

describe('Formats (FA-81)', () => {
  it('has a section with description and example for every generator of the registry', () => {
    const page = renderFormats();
    for (const def of createDefaultRegistry().list()) {
      const section = page.querySelector(`#format-${def.id}`);
      expect(section, def.id).not.toBeNull();
      expect(section?.textContent).toContain(def.name.en);
      expect(section?.textContent).toContain(def.description.en);
      expect(section?.querySelector('.format-example pre, .format-example svg'), `example of ${def.id}`).not.toBeNull();
    }
  });

  it('shows what the core generates (a compact notation line for the built-in net)', () => {
    const compact = renderFormats().querySelector('#format-compact .format-example pre')?.textContent ?? '';
    expect(compact).toContain('places:');
    expect(compact).toContain('p1');
  });

  it('finds every reference document in the build', async () => {
    for (const file of ['json-representation.md', 'json-representation.schema.json', 'mermaid-representation.md', 'compact-notation.md', 'verbalization.md', 'diagram.md', 'structure-report.md', 'structure-report.schema.json', 'bundle.md', 'bundle.schema.json']) {
      expect((await loadDoc(file))?.length, file).toBeGreaterThan(100);
    }
    expect(await loadDoc('m2-plan.md')).toBeNull();
  });

  it('has the page in German', () => {
    setLang('de');
    const page = renderFormats();
    expect(page.querySelector('h1')?.textContent).toBe('Formate');
    expect(page.querySelector('#format-json h2')?.textContent).toBe(createDefaultRegistry().get('json').name.de);
  });
});

describe('example descriptions in German (H75)', () => {
  it('has a German text for every example, different from the English one', () => {
    const examples = listExamples();
    expect(Object.keys(EXAMPLE_DESCRIPTIONS_DE).sort()).toEqual(examples.map((e) => e.path).sort());
    for (const e of examples) {
      expect(e.descriptionDe, e.path).not.toBe('');
      setLang('de');
      expect(describeExample(e)).toBe(e.descriptionDe);
      setLang('en');
      expect(describeExample(e)).toBe(e.description);
    }
  });
});
